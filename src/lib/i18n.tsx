export const DICTS: Record<LangCode, Dict> = {
  en, lt, lv, et, pl, de, fr, es, it, pt, nl, sv, fi, da, no, cs, ro, el, uk,
};

type Ctx = { lang: LangCode; setLang: (l: LangCode) => void; t: (k: string) => string };

const LanguageContext = createContext<Ctx | null>(null);

const STORAGE_KEY = "jw-lang";

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    const saved = localStorage.getItem(STORAGE_KEY) as LangCode | null;
    if (saved && DICTS[saved]) setLangState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const translate = useCallback((k: string) => DICTS[lang]?.[k] ?? en[k] ?? k, [lang]);

  const value = useMemo(() => ({ lang, setLang, t: translate }), [lang, setLang, translate]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used inside LanguageProvider");
  return ctx;
}
